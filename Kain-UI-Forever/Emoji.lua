local function EmojiWrapAddMessage(frame)

	if not KUI.CHAT_ADDMESSAGE_WRAPS then return end
	if not frame or emojiWrappedFrames[frame] or type(frame.AddMessage) ~= "function" then return end

	if KUI.IsChatLockedDown and KUI:IsChatLockedDown() then return end
	if KUI.RememberChatAddMessage then KUI:RememberChatAddMessage(frame) end
	emojiWrappedFrames[frame] = true
	local original = frame.AddMessage
	frame.AddMessage = function(self, text, ...)
		if not KUI.db or KUI.db.emojiChat ~= false then
			text = ConvertEmojiText(text)
		end
		return original(self, text, ...)
	end
end

local function GetAllChatFramesForEmoji()
	local frames = {}
	if type(_G.CHAT_FRAMES) == "table" then
		for _, name in ipairs(_G.CHAT_FRAMES) do
