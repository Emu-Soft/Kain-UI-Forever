			if frame then table.insert(frames, frame) end
		end
	end
	if #frames > 0 then return frames end
	local upper = math.max(_G.NUM_CHAT_WINDOWS or 10, 10) + 20
	for i = 1, upper do
		local frame = _G["ChatFrame" .. i]
		if frame then table.insert(frames, frame) end
	end
	return frames
end

