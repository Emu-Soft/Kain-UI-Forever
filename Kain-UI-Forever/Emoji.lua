local editBoxHooked = setmetatable({}, { __mode = "k" })

local SHORTCODE_HIGHLIGHT_COLOR = "|cff33ff99"
local SHORTCODE_HIGHLIGHT_PATTERN = SHORTCODE_HIGHLIGHT_COLOR .. ":([%a][%w_]*):|r"

local function ExpandHighlightedShortcodes(text)
	return (text:gsub(SHORTCODE_HIGHLIGHT_PATTERN, function(code)
		return EMOJI_SHORTCODES[code:lower()] or (":" .. code .. ":")
	end))
end

local function TryExpandShortcode(editBox)
	local text = editBox:GetText()
	local before, code = text:match("^(.-)%:([%a][%w_]*)%:$")
	if not code then return end
	local emoji = EMOJI_SHORTCODES[code:lower()]
	if not emoji then return end
	local cursorWasAtEnd = editBox:GetCursorPosition() == #text

	local highlighted = SHORTCODE_HIGHLIGHT_COLOR .. ":" .. code .. ":|r"
	editBox:SetText(before .. highlighted)
	if cursorWasAtEnd then
		editBox:SetCursorPosition(#editBox:GetText())
	end
end

local function GetChatEditBoxForEmoji(frame)
	local name = frame.GetName and frame:GetName()
	local byName = name and _G[name .. "EditBox"]
	if byName then return byName end
	return frame.editBox
end

local function InstallShortcodeExpansion(frame)
	local editBox = GetChatEditBoxForEmoji(frame)
	if not editBox or editBoxHooked[editBox] then return end
	editBoxHooked[editBox] = true
	editBox:HookScript("OnChar", function(self)
		if (not KUI.db or KUI.db.emojiChat ~= false)
			and not (KUI.IsChatLockedDown and KUI:IsChatLockedDown()) then
			TryExpandShortcode(self)
		end
	end)

	editBox:HookScript("OnKeyDown", function(self, key)
		if key ~= "ENTER" and key ~= "NUMPADENTER" then return end
		if KUI.db and KUI.db.emojiChat == false then return end
		if KUI.IsChatLockedDown and KUI:IsChatLockedDown() then return end
		local text = self:GetText()
		local converted = ExpandHighlightedShortcodes(text)
		if converted ~= text then self:SetText(converted) end
	end)
end

function KUI:EnsureEmojiShortcodeExpansion()
	for _, frame in ipairs(GetAllChatFramesForEmoji()) do
		InstallShortcodeExpansion(frame)
	end
end
KUI:EnsureEmojiShortcodeExpansion()

