	for _, m in ipairs(emojiMatchList) do
		if text:find(m.seq, 1, true) then
			text = text:gsub(m.seq, m.replacement)
			changed = true
		end
	end
	return text, changed
end
KUI.ReplaceEmojiInText = ReplaceEmojiInText

local shortcodeReplacements = {}
for code, char in pairs(EMOJI_SHORTCODES) do
	local entry = EMOJI_REGISTRY[char]
	if entry then
		shortcodeReplacements[code:lower()] = "|T" .. ICON_PATH .. entry.file .. ":" .. ICON_SIZE .. "|t"
	end
end

local function ReplaceShortcodesInText(text)
	local changed = false
	text = text:gsub("%:([%a][%w_]*)%:", function(code)
		local replacement = shortcodeReplacements[code:lower()]
		if replacement then
			changed = true
			return replacement
		end
		return nil
	end)
	return text, changed
end
KUI.ReplaceShortcodesInText = ReplaceShortcodesInText

local ASCII_EMOTICON_LIST = {
	{ seq = ":-)", char = "🙂" },
	{ seq = ":)", char = "🙂" },
	{ seq = ";-)", char = "😉" },
	{ seq = ";)", char = "😉" },
	{ seq = ":-D", char = "😄" },
	{ seq = ":D", char = "😄" },
	{ seq = ":-P", char = "😛" },
	{ seq = ":P", char = "😛" },
	{ seq = ":p", char = "😛" },
	{ seq = ":-/", char = "😕" },
	{ seq = ":/", char = "😕" },
	{ seq = ":-|", char = "😐" },
	{ seq = ":|", char = "😐" },
	{ seq = ":'(", char = "😢" },
	{ seq = ":-(", char = "🙁" },
	{ seq = ":(", char = "🙁" },
	{ seq = "D:", char = "😧" },
	{ seq = ":-O", char = "😮" },
	{ seq = ":O", char = "😮" },
	{ seq = ":o", char = "😮" },
}

local asciiEmoticonMatchList = {}
for _, entry in ipairs(ASCII_EMOTICON_LIST) do
	local icon = EMOJI_REGISTRY[entry.char]
	if icon then
		table.insert(asciiEmoticonMatchList, {
			seq = entry.seq,
			replacement = "|T" .. ICON_PATH .. icon.file .. ":" .. ICON_SIZE .. "|t",
		})
	end
end
table.sort(asciiEmoticonMatchList, function(a, b) return #a.seq > #b.seq end)

local function IsWordByte(c)
	return c ~= nil and c:match("%w") ~= nil
end

local function ReplaceAsciiEmoticonsInText(text)
	local changed = false
	local out, outLen = {}, 0
	local i, len = 1, #text
	while i <= len do
		local matchedSeq, matchedReplacement
		for _, m in ipairs(asciiEmoticonMatchList) do
			local seqLen = #m.seq
			local stop = i + seqLen - 1
			if stop <= len and text:sub(i, stop) == m.seq then
				local before = i > 1 and text:sub(i - 1, i - 1) or nil
				local after = stop < len and text:sub(stop + 1, stop + 1) or nil
				local ok = true
				if m.seq:match("^%a") and IsWordByte(before) then ok = false end
				if ok and IsWordByte(after) then ok = false end
				if ok and (m.seq == ":/" or m.seq == ":-/") and after == "/" then ok = false end
				if ok then
					matchedSeq, matchedReplacement = m.seq, m.replacement
					break
				end
			end
		end
		if matchedReplacement then
			outLen = outLen + 1
			out[outLen] = matchedReplacement
			i = i + #matchedSeq
			changed = true
		else
			outLen = outLen + 1
			out[outLen] = text:sub(i, i)
			i = i + 1
		end
	end
	if not changed then return text, false end
	return table.concat(out), true
end
KUI.ReplaceAsciiEmoticonsInText = ReplaceAsciiEmoticonsInText

local emojiWrappedFrames = setmetatable({}, { __mode = "k" })
local emojiScanCount = 0

local function ConvertEmojiText(text)
	if type(text) ~= "string" then return text, false end
	local ok1, afterShortcodes, changed1 = pcall(ReplaceShortcodesInText, text)
	if ok1 and afterShortcodes then text = afterShortcodes end
	local ok2, afterAscii, changed2 = pcall(ReplaceAsciiEmoticonsInText, text)
	if ok2 and afterAscii then text = afterAscii end
	local ok3, afterEmoji, changed3 = pcall(ReplaceEmojiInText, text)
	if ok3 and afterEmoji then text = afterEmoji end
	local changed = (ok1 and changed1) or (ok2 and changed2) or (ok3 and changed3)
	if changed then emojiScanCount = emojiScanCount + 1 end
	return text, changed
end

